function build_replay3d_slx(mdl, cena, fps)
%BUILD_REPLAY3D_SLX  Constroi pwt_replay3d.slx: From Workspace -> VR Sink.
%
%   build_replay3d_slx
%
%   O modelo NAO simula fisica nenhuma: ele so toca, no relogio do Simulink,
%   a pose ja calculada por prepara_replay3d. Rodar assim:
%
%       out = sim('pwtsimplificado');
%       R   = prepara_replay3d(out, 60);
%       sim('pwt_replay3d');
%
%   O bloco From Workspace le a expressao 'R.FromWorkspace' direto do base
%   workspace, uma matriz [t, 39] cujas colunas seguem R.mapa.

if nargin < 1 || isempty(mdl),  mdl  = 'pwt_replay3d'; end
if nargin < 2 || isempty(cena), cena = 'amp226.wrl';   end
if ~isfile(cena) && ~isempty(which(cena)), cena = which(cena); end   % acha a cena pelo path
if nargin < 3 || isempty(fps),  fps  = 60;             end

Ts = 1/fps;

% campos da cena, na MESMA ordem das colunas de R.M / R.mapa
campos = { 'Carro.translation', 3
           'Carro.rotation',    4
           'Pitch.rotation',    4
           'Roll.rotation',     4
           'Est_DE.rotation',   4
           'Est_DD.rotation',   4
           'Gir_DE.rotation',   4
           'Gir_DD.rotation',   4
           'Gir_TE.rotation',   4
           'Gir_TD.rotation',   4
           'CamMapa.translation', 3 };
larguras = [campos{:,2}];

if bdIsLoaded(mdl), close_system(mdl, 0); end
if exist([mdl '.slx'],'file'), delete([mdl '.slx']); end
new_system(mdl);
load_system('simulink'); load_system('vrlib');

% ---------------- blocos ----------------
add_block('simulink/Sources/From Workspace', [mdl '/Pose'], ...
    'Position', [60 100 190 150], ...
    'VariableName', 'R.FromWorkspace', ...
    'SampleTime',   num2str(Ts), ...
    'OutputAfterFinalValue', 'Holding final value', ...
    'Interpolate',  'on');

add_block('simulink/Signal Routing/Demux', [mdl '/Separa'], ...
    'Position', [260 60 265 400], ...
    'Outputs',  mat2str(larguras));

add_block('vrlib/VR Sink', [mdl '/Cena 3D'], ...
    'Position',      [400 60 560 400], ...
    'WorldFileName', cena, ...
    'FieldsWritten', strjoin(campos(:,1)', '#'), ...
    'SampleTime',    num2str(Ts), ...
    'ViewEnable',    'off', ...
    'RemoteView',    'off');

% ---------------- fiacao ----------------
add_line(mdl, 'Pose/1', 'Separa/1', 'autorouting','on');
for k = 1:size(campos,1)
    add_line(mdl, sprintf('Separa/%d',k), sprintf('Cena 3D/%d',k), 'autorouting','on');
end

% ---------------- solver e ritmo ----------------
set_param(mdl, ...
    'SolverType',   'Fixed-step', ...
    'Solver',       'FixedStepDiscrete', ...
    'FixedStep',    num2str(Ts), ...
    'StartTime',    '0', ...
    'StopTime',     'R.t(end)', ...
    'EnablePacing', 'on', ...
    'PacingRate',   '1');

% abre a janela 3D no inicio (o VR Sink sozinho nao abre mais nada no R2025a)
set_param(mdl, 'StartFcn', 'abrir_janela3d(1.5);');

% ---------------- anotacao ----------------
txt = sprintf([ ...
 'REPLAY 3D DO AMP-226\n' ...
 '--------------------------------------------------\n' ...
 'Este modelo nao calcula nada. Ele so TOCA a pose ja\n' ...
 'gravada, no relogio do Simulink, com ritmo 1x.\n\n' ...
 'Como usar:\n' ...
 '   out = sim(''pwtsimplificado'');\n' ...
 '   R   = prepara_replay3d(out, %d);\n' ...
 '   sim(''%s'');\n\n' ...
 'A matriz R.FromWorkspace e [t, 42]; a ordem das\n' ...
 'colunas esta em R.mapa e bate com o Demux ao lado.\n\n' ...
 'Convencoes ja aplicadas em prepara_replay3d:\n' ...
 '   vrml_x=+X   vrml_y=altura   vrml_z=-Y\n' ...
 '   psi e delta entram diretos\n' ...
 '   roll, pitch e giro das rodas entram INVERTIDOS\n\n' ...
 'R2025a: o visualizador classico do SL3D foi removido,\n' ...
 'entao ViewEnable esta off e quem abre a janela e o\n' ...
 'StartFcn, chamando abrir_janela3d. Para gerar video,\n' ...
 'use animar_replay3d(R, struct(''video'',''volta.mp4'')).'], fps, mdl);

add_block('built-in/Note', [mdl '/nota'], 'Position',[60 240 60 240]);
a = find_system(mdl,'FindAll','on','Type','annotation');
set_param(a(1), 'Text', txt, 'HorizontalAlignment','left', ...
    'FontName','Consolas', 'FontSize', 9, ...
    'BackgroundColor','lightBlue', 'DropShadow','on', ...
    'Position', [55 200 420 470]);

Simulink.BlockDiagram.arrangeSystem(mdl);
save_system(mdl);
fprintf('modelo criado: %s.slx  (%d campos, Ts = %g s)\n', mdl, size(campos,1), Ts);
end
